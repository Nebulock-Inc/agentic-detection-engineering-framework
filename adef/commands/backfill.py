"""``adef backfill`` — populate skeleton journals for existing rules in an external store.

Per the project decision logged in ``ISA.md``: ship the backfill in v0.1.0 so
``adef memory search`` is immediately useful for the existing rule corpus rather
than empty until each rule earns a journal.
"""

from __future__ import annotations

from pathlib import Path

import click
from rich.console import Console

from adef.core.journal import Journal, workspace_journals_dir

console = Console()


@click.group()
def backfill() -> None:
    """Backfill commands — generate journals for pre-existing detection rules."""


@backfill.command("journals")
@click.option(
    "--workspace",
    type=click.Path(file_okay=False, path_type=Path),
    default=None,
    help="ADEF workspace path (defaults to current dir or ~/work/adef-workspace/).",
)
@click.option(
    "--rule-root",
    type=click.Path(file_okay=False, path_type=Path),
    default=None,
    help="Path to the external rule-store root (overrides ADEF_RULE_ROOT).",
)
@click.option("--limit", type=int, default=0, help="Backfill at most N rules (0 = all).")
@click.option("--dry-run", is_flag=True, help="Print plan without writing files.")
def journals_cmd(
    workspace: Path | None,
    rule_root: Path | None,
    limit: int,
    dry_run: bool,
) -> None:
    """Create skeleton journals for every external rule that doesn't already have one."""
    journals_dir = workspace_journals_dir(workspace)
    journal = Journal(journals_dir)

    from adef.core.rule_bridge import iter_rules

    plan: list[tuple[str, str, str]] = []  # (detection_id, title, rule_uuid)
    next_idx = journal.max_detection_index() + 1

    for rule in iter_rules(rule_root):
        if journal.find_by_rule_uuid(rule.uuid) is not None:
            continue
        detection_id = f"D-{next_idx:04d}"
        plan.append((detection_id, rule.name, rule.uuid))
        next_idx += 1
        if limit and len(plan) >= limit:
            break

    if not plan:
        console.print("[yellow]Nothing to backfill[/yellow] — every rule already has a journal.")
        return

    if dry_run:
        for det_id, name, uuid in plan:
            console.print(f"  {det_id}  {name}  ({uuid})")
        console.print(f"[bold]{len(plan)}[/bold] journals would be created.")
        return

    for det_id, name, uuid in plan:
        journal.create(
            detection_id=det_id,
            title=name,
            owner="",
            rule_uuid=uuid,
            note="Skeleton journal generated by `adef backfill journals`.",
        )

    console.print(f"[green]Created[/green] {len(plan)} skeleton journals under {journals_dir}.")


__all__ = ["backfill"]
